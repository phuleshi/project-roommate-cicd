function resolveKey(target, key) {
  return key.split(".").reduce((result, part) => result?.[part], target);
}

function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_match, token) => {
    return params[token] ?? "";
  });
}

export function getStoredLanguage() {
  if (typeof window === "undefined") return "vi";

  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return stored === "en" || stored === "vi" ? stored : "vi";
}

export function setStoredLanguage(language) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

export function tForLanguage(language, key, params = {}) {
  const catalog = translations[language] || translations.vi;
  const template = resolveKey(catalog, key) ?? resolveKey(translations.vi, key) ?? key;
  return interpolate(template, params);
}

export function translateApiMessage(message, language = getStoredLanguage()) {
  const key = apiMessageKeys[message];
  if (!key) return message;

  return tForLanguage(language, key);
}
